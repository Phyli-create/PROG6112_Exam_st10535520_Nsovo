    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // TODO add your handling code here:
        String customer = txtCustomerName.getText();
String product = cmbProduct.getSelectedItem().toString();

double price = Double.parseDouble(txtPrice.getText());

double vat = price * 0.15;
double commission = price * 0.05;
double total = price + vat + commission;

txtVAT.setText(String.valueOf(vat));
txtCommission.setText(String.valueOf(commission));
txtTotal.setText(String.valueOf(total));

try {
    java.io.FileWriter fw = new java.io.FileWriter("data.txt", true);
    java.io.PrintWriter pw = new java.io.PrintWriter(fw);

    pw.println(customer + "," + product + "," + vat + "," + commission + "," + total);

    pw.close();
} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error saving data");
}
    }//GEN-LAST:event_btnProcessActionPerformed

